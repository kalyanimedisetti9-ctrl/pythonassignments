from abc import ABC, abstractmethod

class Shape(ABC):
    @abstractmethod
    def area(self):
        pass

class Circle(Shape):
    def area(self):
        return 3.14 * 5 * 5

class Rectangle(Shape):
    def area(self):
        return 10 * 5

shapes = [Circle(), Rectangle()]

for shape in shapes:
    print("Area:", shape.area())